def run_migrations():
    """
    Executes all table creation DDL, security policies, and seed data
    against the configured DATABASE_URL.
    """
    db_url = get_database_url()
    if not db_url:
        return {
            "success": False,
            "configured": False,
            "error": "DATABASE_URL is not set in environment.",
            "note": "Configure DATABASE_URL in Render environment variables."
        }

    conn, driver_or_err = get_postgres_connection()
    if conn is None:
        return {
            "success": False,
            "configured": True,
            "error": f"Failed to connect: {driver_or_err}",
            "database_url_masked": db_url[:12] + "..." if len(db_url) > 12 else "***"
        }

    driver_name = driver_or_err
    created_tables = []
    errors = []

    try:
        if driver_name == "psycopg2":
            with conn.cursor() as cur:
                # 1. Create tables
                cur.execute(SQL_CREATE_ALL_TABLES)
                # 2. Add policies and storage bucket
                cur.execute(SQL_POLICIES_AND_BUCKET)
                # 3. Seed data
                cur.execute(SQL_SEED_DATA)

                # 4. Count existing tables in public schema
                cur.execute("""
                    SELECT table_name 
                    FROM information_schema.tables 
                    WHERE table_schema = 'public' 
                    ORDER BY table_name;
                """)
                rows = cur.fetchall()
                created_tables = [r[0] for r in rows]
            conn.close()

        elif driver_name == "pg8000":
            # pg8000 native connection
            conn.run(SQL_CREATE_ALL_TABLES)
            conn.run(SQL_POLICIES_AND_BUCKET)
            conn.run(SQL_SEED_DATA)

            rows = conn.run("""
                SELECT table_name 
                FROM information_schema.tables 
                WHERE table_schema = 'public' 
                ORDER BY table_name;
            """)
            created_tables = [r[0] for r in rows]
            conn.close()

        return {
            "success": True,
            "configured": True,
            "driver": driver_name,
            "message": f"Successfully initialized {len(created_tables)} tables in PostgreSQL database via server!",
            "total_tables": len(created_tables),
            "tables": created_tables,
            "metadata": TABLES_METADATA
        }

    except Exception as exec_err:
        try:
            conn.close()
        except Exception:
            pass
        return {
            "success": False,
            "configured": True,
            "error": f"Migration execution error: {str(exec_err)}",
            "driver": driver_name
        }

def get_database_status_and_tables():
    """Returns the current connection status and row counts of all tables."""
    db_url = get_database_url()
    if not db_url:
        return {
            "configured": False,
            "mode": "sqlite_fallback",
            "message": "DATABASE_URL not set. Running with local SQLite orders.db."
        }

    conn, driver_or_err = get_postgres_connection()
    if conn is None:
        return {
            "configured": True,
            "connected": False,
            "error": driver_or_err,
            "mode": "sqlite_fallback"
        }

    driver_name = driver_or_err
    table_counts = {}
    table_list = []

    try:
        if driver_name == "psycopg2":
            with conn.cursor() as cur:
                cur.execute("""
                    SELECT table_name 
                    FROM information_schema.tables 
                    WHERE table_schema = 'public' 
                    ORDER BY table_name;
                """)
                table_list = [r[0] for r in cur.fetchall()]

                for t in table_list:
                    try:
                        cur.execute(f"SELECT COUNT(*) FROM public.{t};")
                        table_counts[t] = cur.fetchone()[0]
                    except Exception:
                        table_counts[t] = 0
            conn.close()

        elif driver_name == "pg8000":
            rows = conn.run("""
                SELECT table_name 
                FROM information_schema.tables 
                WHERE table_schema = 'public' 
                ORDER BY table_name;
            """)
            table_list = [r[0] for r in rows]
            for t in table_list:
                try:
                    c_rows = conn.run(f"SELECT COUNT(*) FROM public.{t};")
                    table_counts[t] = c_rows[0][0] if c_rows else 0
                except Exception:
                    table_counts[t] = 0
            conn.close()

        return {
            "configured": True,
            "connected": True,
            "driver": driver_name,
            "total_tables": len(table_list),
            "tables": table_list,
            "counts": table_counts
        }

    except Exception as err:
        try:
            conn.close()
        except Exception:
            pass
        return {
            "configured": True,
            "connected": False,
            "error": str(err),
            "mode": "sqlite_fallback"
        }
