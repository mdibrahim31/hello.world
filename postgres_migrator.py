def get_database_url():
    """Retrieves and normalizes DATABASE_URL from environment."""
    url = (
        os.getenv("DATABASE_URL")
        or os.getenv("POSTGRES_URL")
        or os.getenv("POSTGRESQL_URL")
        or os.getenv("SUPABASE_DB_URL", "")
    ).strip()
    return url

def get_postgres_connection():
    """
    Establishes a connection to PostgreSQL using psycopg2 or pg8000.
    Returns (connection, driver_name) or (None, error_str).
    """
    db_url = get_database_url()
    if not db_url:
        return None, "DATABASE_URL environment variable is not set."

    # Fix potential postgres:// vs postgresql:// prefix
    normalized_url = db_url
    if normalized_url.startswith("postgres://"):
        normalized_url = "postgresql://" + normalized_url[len("postgres://"):]

    # 1. Try psycopg2 if installed
    if _has_psycopg2:
        try:
            # Ensure sslmode requirement for Supabase / Cloud hosts
            conn_dsn = normalized_url
            if "sslmode" not in conn_dsn and "@" in conn_dsn:
                separator = "&" if "?" in conn_dsn else "?"
                conn_dsn = f"{conn_dsn}{separator}sslmode=require"

            conn = psycopg2.connect(conn_dsn)
            conn.autocommit = True
            return conn, "psycopg2"
        except Exception as err:
            psycopg2_err = str(err)
            print(f"⚠️ [postgres_migrator] psycopg2 connection failed: {psycopg2_err}")
            # Try plain URL without appending sslmode if it caused parse issues
            try:
                conn = psycopg2.connect(normalized_url)
                conn.autocommit = True
                return conn, "psycopg2"
            except Exception:
                pass

    # 2. Try pg8000 pure-python driver if available
    if _has_pg8000:
        try:
            parsed = urllib.parse.urlparse(normalized_url)
            import ssl
            ssl_ctx = ssl.create_default_context()
            ssl_ctx.check_hostname = False
            ssl_ctx.verify_mode = ssl.CERT_NONE

            conn = pg8000.native.Connection(
                user=urllib.parse.unquote(parsed.username or "postgres"),
                password=urllib.parse.unquote(parsed.password or ""),
                host=parsed.hostname or "localhost",
                port=parsed.port or 5432,
                database=parsed.path.lstrip("/") or "postgres",
                ssl_context=ssl_ctx
            )
            return conn, "pg8000"
        except Exception as pg_err:
            print(f"⚠️ [postgres_migrator] pg8000 connection failed: {pg_err}")

    driver_status = f"Drivers available: psycopg2={_has_psycopg2}, pg8000={_has_pg8000}"
    return None, f"No working PostgreSQL driver found or connection failed. {driver_status}"

